-- Tabla de auditoria de tarifas
CREATE TABLE auditoria_tarifa (
  id_auditoria   NUMBER GENERATED BY DEFAULT AS IDENTITY,
  usuario        VARCHAR2(50),
  fecha          TIMESTAMP DEFAULT SYSTIMESTAMP,
  id_habitacion  NUMBER,
  id_temporada   NUMBER,
  valor_anterior NUMBER(12,2),
  valor_nuevo    NUMBER(12,2),
  CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria)
);

-- Disparador 1: auditoria de cambios de precio (compuesto: fila + sentencia).
CREATE OR REPLACE TRIGGER trg_auditoria_tarifa
FOR UPDATE OF valor_noche ON tarifa
COMPOUND TRIGGER
  TYPE t_reg IS RECORD (id_habitacion NUMBER, id_temporada NUMBER,
                        valor_anterior NUMBER(12,2), valor_nuevo NUMBER(12,2));
  TYPE t_tab IS TABLE OF t_reg INDEX BY PLS_INTEGER;
  g_cambios t_tab;

  AFTER EACH ROW IS
    v_reg t_reg;
  BEGIN
    IF :OLD.valor_noche <> :NEW.valor_noche THEN
      v_reg.id_habitacion  := :NEW.id_habitacion;
      v_reg.id_temporada   := :NEW.id_temporada;
      v_reg.valor_anterior := :OLD.valor_noche;
      v_reg.valor_nuevo    := :NEW.valor_noche;
      g_cambios(g_cambios.COUNT+1) := v_reg;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
  BEGIN
    FOR i IN 1..g_cambios.COUNT LOOP
      INSERT INTO auditoria_tarifa(usuario,id_habitacion,id_temporada,valor_anterior,valor_nuevo)
      VALUES (USER,g_cambios(i).id_habitacion,g_cambios(i).id_temporada,
              g_cambios(i).valor_anterior,g_cambios(i).valor_nuevo);
    END LOOP;
    g_cambios.DELETE;
  END AFTER STATEMENT;
END trg_auditoria_tarifa;
/

-- Disparador 2: impedir solape de habitaciones (valida al terminar la sentencia, sin
-- AUTONOMOUS_TRANSACTION). Solo cuenta reservas CONFIRMADA o COMPLETADA.
CREATE OR REPLACE TRIGGER trg_evitar_solape
FOR INSERT OR UPDATE OF id_habitacion, fecha_checkin, fecha_checkout, id_reserva ON reserva_habitacion
COMPOUND TRIGGER
  TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  g_ids t_ids;

  AFTER EACH ROW IS
  BEGIN
    g_ids(g_ids.COUNT+1) := :NEW.id_reserva_habitacion;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_conflictos NUMBER;
  BEGIN
    FOR i IN 1..g_ids.COUNT LOOP
      SELECT COUNT(*) INTO v_conflictos
        FROM reserva_habitacion nueva
        JOIN reserva rn ON rn.id_reserva=nueva.id_reserva AND rn.estado IN ('CONFIRMADA','COMPLETADA')
        JOIN reserva_habitacion otra
          ON otra.id_habitacion=nueva.id_habitacion
         AND otra.id_reserva_habitacion<>nueva.id_reserva_habitacion
         AND otra.fecha_checkin<nueva.fecha_checkout AND otra.fecha_checkout>nueva.fecha_checkin
        JOIN reserva ro ON ro.id_reserva=otra.id_reserva AND ro.estado IN ('CONFIRMADA','COMPLETADA')
       WHERE nueva.id_reserva_habitacion=g_ids(i);
      IF v_conflictos > 0 THEN
        g_ids.DELETE;
        RAISE_APPLICATION_ERROR(-20004,'Trigger: la habitacion ya esta ocupada en esas fechas.');
      END IF;
    END LOOP;
    g_ids.DELETE;
  END AFTER STATEMENT;
END trg_evitar_solape;
/

-- Complemento: valida el paso PENDIENTE -> CONFIRMADA/COMPLETADA.
CREATE OR REPLACE TRIGGER trg_confirmar_sin_solape
FOR UPDATE OF estado ON reserva
COMPOUND TRIGGER
  TYPE t_ids IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
  g_ids t_ids;

  AFTER EACH ROW IS
  BEGIN
    IF :NEW.estado IN ('CONFIRMADA','COMPLETADA') AND :OLD.estado NOT IN ('CONFIRMADA','COMPLETADA') THEN
      g_ids(g_ids.COUNT+1) := :NEW.id_reserva;
    END IF;
  END AFTER EACH ROW;

  AFTER STATEMENT IS
    v_conflictos NUMBER;
  BEGIN
    FOR i IN 1..g_ids.COUNT LOOP
      SELECT COUNT(*) INTO v_conflictos
        FROM reserva_habitacion nueva
        JOIN reserva_habitacion otra
          ON otra.id_habitacion=nueva.id_habitacion
         AND otra.id_reserva<>nueva.id_reserva
         AND otra.fecha_checkin<nueva.fecha_checkout AND otra.fecha_checkout>nueva.fecha_checkin
        JOIN reserva ro ON ro.id_reserva=otra.id_reserva AND ro.estado IN ('CONFIRMADA','COMPLETADA')
       WHERE nueva.id_reserva=g_ids(i);
      IF v_conflictos > 0 THEN
        g_ids.DELETE;
        RAISE_APPLICATION_ERROR(-20004,'Trigger: no se puede confirmar, la habitacion ya esta ocupada en esas fechas.');
      END IF;
    END LOOP;
    g_ids.DELETE;
  END AFTER STATEMENT;
END trg_confirmar_sin_solape;
/
